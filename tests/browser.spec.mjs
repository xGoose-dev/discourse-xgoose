import { test, expect } from "@playwright/test";
const password = process.env.XGOOSE_TEST_PASSWORD;
test.skip(!password, "Requires the isolated synthetic development fixture.");
const baseURL = process.env.XGOOSE_TEST_BASE_URL || "http://localhost:3000";
async function login(page) {
  const csrf = await (await page.request.get("/session/csrf.json")).json();
  const response = await page.request.post("/session.json", {
    form: { login: "xgoose_demo", password },
    headers: {
      "X-CSRF-Token": csrf.csrf,
      "X-Requested-With": "XMLHttpRequest",
      Origin: baseURL,
    },
  });
  expect((await response.json()).user?.username).toBe("xgoose_demo");
}
test("guest panel explains login and fits a phone viewport", async ({
  page,
}) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto("/");
  await page.getByRole("button", { name: "Open xGoose", exact: true }).click();
  await expect(page.locator("#xgoose-panel")).toContainText(
    "Log in to the forum",
  );
  expect(
    await page
      .locator("#xgoose-panel")
      .evaluate((e) => e.getBoundingClientRect().width),
  ).toBeLessThanOrEqual(390);
  await page.keyboard.press("Escape");
  await expect(page.locator("#xgoose-panel")).toHaveCount(0);
});
test("real Pi tool loop searches, reads, cites, and exports a complete server transcript", async ({
  page,
}) => {
  const errors = [];
  page.on("pageerror", (e) => errors.push(e.message));
  await login(page);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/");
  await page.locator(".xgoose-launcher").click();
  await page
    .locator("#xgoose-input")
    .fill("What does the community recommend about finding reliable answers?");
  const sessionCreated = page.waitForResponse(
    (r) =>
      r.url().endsWith("/xgoose/sessions") && r.request().method() === "POST",
  );
  await page.locator(".xgoose-panel button[type=submit]").click();
  const session = await (await sessionCreated).json();
  await expect(page.locator(".xgoose-thread")).toContainText(
    "This response was generated by the local test provider.",
    { timeout: 90000 },
  );
  await expect(page.locator(".xgoose-panel button[type=submit]")).toBeVisible();
  await expect(page.locator(".xgoose-error")).toHaveCount(0);
  await expect(
    page.locator('.xgoose-message[data-role=assistant] a[href*="/t/"]'),
  ).toHaveCount(1);
  await expect(page.locator(".xgoose-tools")).toContainText("Search forum");
  await expect(page.locator(".xgoose-tools")).toContainText("Read topic");
  await expect(
    page.locator(".xgoose-message[data-role=assistant]").last(),
  ).toBeInViewport();
  const exported = await page.request.get(
    `/admin/plugins/xgoose/${session.id}.json`,
  );
  expect(exported.status()).toBe(200);
  const log = await exported.json();
  expect(log.complete).toBe(true);
  expect(log.requests).toHaveLength(3);
  expect(
    log.requests.every(
      (r) => r.status === "completed" && r.charged_tokens === 160,
    ),
  ).toBe(true);
  expect(log.client_reported_events.map((e) => e.kind)).toContain("tool_end");
  expect(JSON.stringify(log)).not.toContain("local-mock-only");
  await page.screenshot({
    path: "test-results/desktop-mock.png",
    fullPage: true,
  });
  // An ordinary in-app navigation keeps the same in-memory conversation.
  await page.locator(".xgoose-message[data-role=assistant] a").click();
  await expect(page.locator(".xgoose-thread")).toContainText(
    "This response was generated by the local test provider.",
  );
  await page.getByRole("button", { name: "New chat", exact: true }).click();
  await expect(page.locator(".xgoose-message")).toHaveCount(0);
  expect(errors).toEqual([]);
});
test("Chinese translation, dark theme, and mobile panel", async ({ page }) => {
  await login(page);
  await page.goto("/");
  const csrf = await (await page.request.get("/session/csrf.json")).json();
  const headers = {
    "X-CSRF-Token": csrf.csrf,
    "X-Requested-With": "XMLHttpRequest",
    Origin: baseURL,
  };
  const setLocale = async (locale) => {
    const response = await page.request.put("/u/xgoose_demo.json", {
      form: { locale },
      headers,
    });
    expect(response.status()).toBe(200);
  };
  try {
    await setLocale("zh_CN");
    await page.setViewportSize({ width: 390, height: 844 });
    await page.emulateMedia({ colorScheme: "dark" });
    await page.reload();
    await page
      .getByRole("button", { name: "打开 xGoose", exact: true })
      .click();
    await expect(page.locator("#xgoose-panel")).toContainText("想了解什么？");
    expect(
      await page.evaluate(() => document.documentElement.scrollWidth),
    ).toBeLessThanOrEqual(390);
    await page.screenshot({
      path: "docs/screenshots/mobile-zh.png",
      fullPage: false,
    });
  } finally {
    await setLocale("en");
  }
});

test("slow first token survives the ordinary web-worker timeout", async ({
  page,
}) => {
  await login(page);
  await page.goto("/");
  await page.locator(".xgoose-launcher").click();
  await page
    .locator("#xgoose-input")
    .fill("xgoose-delay-test: find reliable community answers");
  await page.locator(".xgoose-panel button[type=submit]").click();
  await expect(
    page.getByRole("button", { name: "Stop", exact: true }),
  ).toBeVisible();
  // The mock waits 65 seconds before its first token. A normal dev worker
  // expires at 60 seconds; the socket belongs to the streaming pool instead.
  const started = Date.now();
  expect((await page.request.get("/site.json")).status()).toBe(200);
  expect(Date.now() - started).toBeLessThan(5000);
  await expect(page.locator(".xgoose-thread")).toContainText(
    "This response was generated by the local test provider.",
    { timeout: 100000 },
  );
  await expect(page.locator(".xgoose-error")).toHaveCount(0);
  expect(Date.now() - started).toBeGreaterThanOrEqual(64000);
});

