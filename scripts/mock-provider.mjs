// Deterministic, local HTTPS OpenAI-compatible mock. No external model calls.
import https from 'node:https';
import fs from 'node:fs';
const server = https.createServer({ key: fs.readFileSync(process.env.XGOOSE_MOCK_KEY), cert: fs.readFileSync(process.env.XGOOSE_MOCK_CERT) }, async (req, res) => {
  if (req.method !== 'POST' || req.url !== '/v1/chat/completions') { res.writeHead(404).end(); return; }
  const chunks = []; for await (const chunk of req) chunks.push(chunk);
  const body = JSON.parse(Buffer.concat(chunks).toString());
  const lastUser = body.messages.findLastIndex(m => m.role === 'user');
  const results = body.messages.slice(lastUser + 1).filter(m => m.role === 'tool');
  let delta, reason;
  if (!results.length) {
    delta = { tool_calls: [{ index: 0, id: 'call_search', type: 'function', function: { name: 'search_forum', arguments: '{"query":"community"}' } }] }; reason = 'tool_calls';
  } else if (results.length === 1) {
    const data = JSON.parse(results[0].content); const id = data.topics?.[0]?.id;
    delta = id ? { tool_calls: [{ index: 0, id: 'call_read', type: 'function', function: { name: 'read_topic', arguments: JSON.stringify({ topic_id: id }) } }] } : { content: 'No matching topics were found.' }; reason = id ? 'tool_calls' : 'stop';
  } else {
    const data = JSON.parse(results.at(-1).content); const post = data.posts?.[0];
    delta = { content: `The community recommends checking original discussions before answering.\n\n- Search for related posts and read the full context.\n- Compare experiences and check the dates of replies.\n- Link to the specific posts that support the answer.\n\n${post ? `[Source: ${data.title}](${post.url})` : 'The available source was incomplete.'}\n\nThis response was generated by the local test provider.` }; reason = 'stop';
  }
  res.writeHead(200, { 'Content-Type': 'text/event-stream', 'Cache-Control': 'no-store' });
  const event = { id: 'mock', object: 'chat.completion.chunk', created: Math.floor(Date.now()/1000), model: body.model, choices: [{ index: 0, delta, finish_reason: reason }] };
  const stream = `data: ${JSON.stringify(event)}\n\ndata: ${JSON.stringify({ choices: [], usage: { prompt_tokens: 100, completion_tokens: 60, total_tokens: 160 } })}\n\ndata: [DONE]\n\n`;
  // Intentionally split inside JSON tokens, including tool arguments.
  for (let n=0; n<stream.length; n+=31) { res.write(stream.slice(n,n+31)); await new Promise(r => setTimeout(r,3)); }
  res.end();
});
server.listen(9443, '0.0.0.0', () => console.log('Local mock listening on 9443'));
