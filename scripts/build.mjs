import { build } from "esbuild";
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
const outfile = "assets/javascripts/discourse/lib/xgoose-agent.js";
const result = await build({
  entryPoints: ["frontend/agent.js"],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: ["es2022"],
  minify: true,
  legalComments: "none",
  outfile,
  metafile: true,
});
const packages = new Map();
for (const input of Object.keys(result.metafile.inputs)) {
  if (!input.includes("node_modules/")) continue;
  let directory = path.dirname(input);
  while (directory !== ".") {
    try {
      const pkg = JSON.parse(
        await readFile(path.join(directory, "package.json"), "utf8"),
      );
      if (pkg.name) {
        if (!packages.has(pkg.name))
          packages.set(pkg.name, { ...pkg, directory });
        break;
      }
      directory = path.dirname(directory);
    } catch {
      directory = path.dirname(directory);
    }
  }
}
let notices = "Bundled third-party licenses. Generated by npm run build.\n";
for (const pkg of [...packages.values()].sort((a, b) =>
  a.name.localeCompare(b.name),
)) {
  notices += `\n${"=".repeat(72)}\n${pkg.name} ${pkg.version} (${pkg.license || "see below"})\n`;
  const licenses = (await readdir(pkg.directory))
    .filter((name) => /^(licen[sc]e|copying|notice)([.-]|$)/i.test(name))
    .sort();
  if (!licenses.length && pkg.name.startsWith("@earendil-works/pi-")) {
    notices += await readFile("docs/pi-MIT.txt", "utf8");
    continue;
  }
  if (!licenses.length)
    throw new Error(`No license file found for bundled package ${pkg.name}`);
  for (const license of licenses)
    notices += `\n${await readFile(path.join(pkg.directory, license), "utf8")}\n`;
}
await writeFile("docs/third-party-licenses.txt", notices);
console.log(`Browser bundle built with notices for ${packages.size} packages`);
